"""
Unit tests for the JSON Report Validation Module (report_validation.py).
"""

import copy
import sys
import unittest
from datetime import datetime, timezone
from pathlib import Path

# Add 'src' to sys.path so tests can import lpe_sentinel modules
SRC_DIR = Path(__file__).resolve().parent.parent / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from lpe_sentinel.models import Finding
from lpe_sentinel.report_validation import ValidationResult, validate_report_data
from lpe_sentinel.reporting import build_report_data


class TestReportValidation(unittest.TestCase):
    """Test suite verifying structure, data type, and summary validation for audit reports."""

    def setUp(self) -> None:
        """Create sample findings and a valid baseline report."""
        self.finding_info = Finding(
            finding_id="SUID-001",
            title="SUID Binary Detected",
            severity="INFO",
            description="A binary has the SUID bit set.",
            evidence="Permissions: -rwsr-xr-x (0o4755)",
            affected_resource="/usr/bin/passwd",
            recommendation="Verify business justification.",
            mitre_attack="T1548.001",
        )

        self.finding_high = Finding(
            finding_id="PERM-001",
            title="World-Writable Configuration File",
            severity="HIGH",
            description="The configuration file is world-writable.",
            evidence="Permissions: -rw-rw-rw- (0o666)",
            affected_resource="/etc/cron.d/job",
            recommendation="Restrict permissions to root.",
            mitre_attack="T1222.002",
        )

        self.valid_system_info = {
            "os_name": "Linux",
            "os_release": "6.6.9",
            "hostname": "audit-node",
            "username": "auditor",
            "python_version": "3.11.8",
            "architecture": "x86_64",
            "platform_category": "Linux",
        }

        self.valid_report = build_report_data(
            [self.finding_info, self.finding_high],
            system_info=self.valid_system_info,
        )

    def test_valid_report_with_findings(self) -> None:
        """Verify that a standard report generated by build_report_data passes validation."""
        result = validate_report_data(self.valid_report)
        self.assertIsInstance(result, ValidationResult)
        self.assertTrue(result.is_valid)
        self.assertEqual(result.errors, [])

    def test_valid_report_empty_findings(self) -> None:
        """Verify that a valid report with zero findings passes validation cleanly."""
        empty_report = build_report_data([])
        result = validate_report_data(empty_report)
        self.assertTrue(result.is_valid)
        self.assertEqual(result.errors, [])

    def test_tuple_unpacking_and_attribute_access(self) -> None:
        """Verify ValidationResult supports both attribute access and tuple unpacking."""
        result = validate_report_data(self.valid_report)
        is_valid, errors = result
        self.assertTrue(is_valid)
        self.assertEqual(errors, [])
        self.assertEqual(result.is_valid, is_valid)
        self.assertEqual(result.errors, errors)

    def test_unexpected_top_level_data_types(self) -> None:
        """Verify that non-dictionary inputs are rejected without crashing."""
        for invalid_input in [None, "string", 123, [1, 2, 3], True, 3.14]:
            with self.subTest(invalid_input=invalid_input):
                result = validate_report_data(invalid_input)
                self.assertFalse(result.is_valid)
                self.assertTrue(any("must be a dictionary" in err for err in result.errors))

    def test_missing_top_level_sections(self) -> None:
        """Verify that missing top-level sections are detected and reported."""
        for section in ["report_metadata", "summary", "system_info", "findings"]:
            with self.subTest(missing_section=section):
                report_copy = copy.deepcopy(self.valid_report)
                del report_copy[section]
                result = validate_report_data(report_copy)
                self.assertFalse(result.is_valid)
                self.assertTrue(
                    any(f"Missing required top-level section: '{section}'" in err for err in result.errors)
                )

    def test_wrong_types_for_top_level_sections(self) -> None:
        """Verify that non-dict or non-list top-level sections are flagged."""
        test_cases = [
            ("report_metadata", "not a dict"),
            ("summary", [1, 2, 3]),
            ("system_info", "not a dict"),
            ("findings", {"not": "a list"}),
        ]
        for section, bad_val in test_cases:
            with self.subTest(section=section, bad_val=bad_val):
                report_copy = copy.deepcopy(self.valid_report)
                report_copy[section] = bad_val
                result = validate_report_data(report_copy)
                self.assertFalse(result.is_valid)
                self.assertTrue(any(section in err for err in result.errors))

    def test_malformed_metadata_fields(self) -> None:
        """Verify validation of required fields in report_metadata."""
        # Missing project_name
        report = copy.deepcopy(self.valid_report)
        del report["report_metadata"]["project_name"]
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("project_name" in err for err in result.errors))

        # Empty version
        report = copy.deepcopy(self.valid_report)
        report["report_metadata"]["version"] = "   "
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("version" in err for err in result.errors))

        # Non-string format_version
        report = copy.deepcopy(self.valid_report)
        report["report_metadata"]["format_version"] = 1.0
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("format_version" in err for err in result.errors))

    def test_malformed_metadata_timestamp(self) -> None:
        """Verify timestamp validation for generated_at."""
        # Non-ISO timestamp
        report = copy.deepcopy(self.valid_report)
        report["report_metadata"]["generated_at"] = "invalid-date-string"
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("not a valid ISO 8601 timestamp" in err for err in result.errors))

        # Naive timestamp without timezone
        report = copy.deepcopy(self.valid_report)
        report["report_metadata"]["generated_at"] = "2026-10-17T12:00:00"
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("must include timezone information" in err for err in result.errors))

    def test_malformed_finding_items(self) -> None:
        """Verify that non-dict finding entries in findings list are rejected."""
        report = copy.deepcopy(self.valid_report)
        report["findings"].append("not_a_finding_dict")  # type: ignore
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("must be a dictionary" in err for err in result.errors))

    def test_finding_missing_required_fields(self) -> None:
        """Verify that missing required finding fields are detected."""
        required_fields = [
            "finding_id",
            "title",
            "severity",
            "description",
            "evidence",
            "affected_resource",
            "recommendation",
        ]
        for field_name in required_fields:
            with self.subTest(missing_field=field_name):
                report = copy.deepcopy(self.valid_report)
                del report["findings"][0][field_name]
                result = validate_report_data(report)
                self.assertFalse(result.is_valid)
                self.assertTrue(any(f"missing required field: '{field_name}'" in err for err in result.errors))

    def test_finding_field_empty_or_wrong_type(self) -> None:
        """Verify that empty string or non-string finding fields are rejected."""
        report = copy.deepcopy(self.valid_report)
        report["findings"][0]["title"] = ""
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("field 'title' must be a non-empty string" in err for err in result.errors))

        report = copy.deepcopy(self.valid_report)
        report["findings"][0]["evidence"] = 12345
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("field 'evidence' must be a non-empty string" in err for err in result.errors))

    def test_finding_invalid_severity(self) -> None:
        """Verify that invalid severity values in findings are rejected."""
        for bad_sev in ["UNKNOWN", "CRIT", "low", 123, ""]:
            with self.subTest(bad_sev=bad_sev):
                report = copy.deepcopy(self.valid_report)
                report["findings"][0]["severity"] = bad_sev
                result = validate_report_data(report)
                self.assertFalse(result.is_valid)
                self.assertTrue(any("severity" in err for err in result.errors))

    def test_finding_mitre_attack_validation(self) -> None:
        """Verify mitre_attack allows valid string or None, but rejects invalid types."""
        # None is valid
        report = copy.deepcopy(self.valid_report)
        report["findings"][0]["mitre_attack"] = None
        result = validate_report_data(report)
        self.assertTrue(result.is_valid)

        # Empty string is invalid
        report = copy.deepcopy(self.valid_report)
        report["findings"][0]["mitre_attack"] = "   "
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("mitre_attack" in err for err in result.errors))

        # Integer is invalid
        report = copy.deepcopy(self.valid_report)
        report["findings"][0]["mitre_attack"] = 1548
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("mitre_attack" in err for err in result.errors))

    def test_summary_total_findings_mismatch(self) -> None:
        """Verify that mismatch between summary.total_findings and findings list is caught."""
        report = copy.deepcopy(self.valid_report)
        report["summary"]["total_findings"] = 99
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("total_findings (99) does not match actual" in err for err in result.errors))

    def test_summary_total_findings_invalid_type(self) -> None:
        """Verify non-integer or boolean values for summary.total_findings are rejected."""
        for bad_total in ["2", True, -1, 2.5]:
            with self.subTest(bad_total=bad_total):
                report = copy.deepcopy(self.valid_report)
                report["summary"]["total_findings"] = bad_total
                result = validate_report_data(report)
                self.assertFalse(result.is_valid)
                self.assertTrue(any("total_findings" in err for err in result.errors))

    def test_summary_severity_counts_mismatch(self) -> None:
        """Verify mismatch between summary.severity_counts and actual findings is caught."""
        report = copy.deepcopy(self.valid_report)
        # Baseline report has 1 INFO and 1 HIGH
        report["summary"]["severity_counts"]["INFO"] = 5
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(
            any("severity_counts['INFO'] (5) does not match actual" in err for err in result.errors)
        )

    def test_summary_severity_counts_missing_or_invalid_values(self) -> None:
        """Verify missing severity key or invalid count types in severity_counts."""
        # Missing severity key
        report = copy.deepcopy(self.valid_report)
        del report["summary"]["severity_counts"]["CRITICAL"]
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("missing count for severity: 'CRITICAL'" in err for err in result.errors))

        # Boolean count
        report = copy.deepcopy(self.valid_report)
        report["summary"]["severity_counts"]["INFO"] = True
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("Severity count for 'INFO' must be a non-negative integer" in err for err in result.errors))

        # Negative count
        report = copy.deepcopy(self.valid_report)
        report["summary"]["severity_counts"]["LOW"] = -1
        result = validate_report_data(report)
        self.assertFalse(result.is_valid)
        self.assertTrue(any("Severity count for 'LOW' must be a non-negative integer" in err for err in result.errors))


if __name__ == "__main__":
    unittest.main()
